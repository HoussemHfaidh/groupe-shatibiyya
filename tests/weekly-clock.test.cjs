const assert=require('node:assert/strict');
const clock=require('../weekly-clock');
const jam=require('../jam-model');
const schedule={number:45,startDate:'2026-09-05',timeZone:'Europe/Paris'};
for (const [day,date,utc] of [[6,'2026-09-05','2026-09-12T04:00:00.000Z'],[0,'2026-09-06','2026-09-13T04:00:00.000Z'],[6,'2026-10-24','2026-10-31T05:00:00.000Z'],[6,'2026-03-28','2026-04-04T04:00:00.000Z']]) assert.equal(clock.deadline({date},day).toISOString(),utc);
const before=new Date('2026-09-12T03:59:59Z'), at=new Date('2026-09-12T04:00:00Z');
assert.equal(jam.weeklyWindow(schedule,before).number,45);
assert.equal(jam.weeklyWindow(schedule,at).number,46);
assert.equal(jam.weeklyWindow(schedule,new Date('2026-09-12T04:00:01Z')).number,46);
assert.equal(jam.weeklyWindow({...schedule,startDate:'2026-09-06'},at).number,45);
const old=jam.ensureWeek({},['A'],schedule,before);
assert.equal(jam.current(old,schedule,at),null);
assert.throws(()=>jam.confirm(Object.values(old)[0],'A',0,{role:'professor'},at));
console.log('✓ 06:00 Paris, before/at/after, Saturday vs Sunday, summer/winter DST, expired Jam');
const maintenance=require('../recitation-maintenance');
const config={students:['A','B'],weeks:[{id:'w',date:'2026-09-05'}],settings:{weekBoundaryDay:6},statuses:{a__w:'done'},loginEmails:{saved:true},groups:{group2:{preserve:true}}};
assert.equal(maintenance.close(config,before),config);
const closed=maintenance.close(config,at);
assert.equal(closed.statuses.a__w,'done');assert.equal(closed.statuses.b__w,'missed');
assert.equal(closed.groups,config.groups);assert.equal(closed.loginEmails,config.loginEmails);
assert.equal(maintenance.close(closed,at),closed);
assert.equal(maintenance.close({...config,weeks:[{id:'w',date:'2026-09-06'}],settings:{weekBoundaryDay:0}},at).statuses.b__w,undefined);
console.log('✓ Closure: red only after deadline, Sunday untouched Saturday, existing data preserved, idempotent');
